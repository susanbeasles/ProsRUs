import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const identityPath = "src/domain/core-operation-identity.ts",
  manifestPath = "integration/core-planner-source.json";
const result = await build({
  entryPoints: [
    "src/domain/core-operation-plan.ts",
    "src/application/core-operation-lifecycle.ts",
  ],
  bundle: true,
  packages: "external",
  platform: "node",
  format: "esm",
  write: false,
  metafile: true,
  outdir: "artifacts/core-planner-identity",
});
const paths = [
  ...new Set([
    ...Object.keys(result.metafile.inputs).filter(
      (path) => path !== identityPath,
    ),
    "package-lock.json",
    "scripts/generate-core-planner-identity.mjs",
  ]),
].sort();
const files = await Promise.all(
  paths.map(async (path) => ({
    path,
    sha256: createHash("sha256")
      .update(await readFile(path))
      .digest("hex"),
  })),
);
const meaning = {
  format: "core-planner-source-v1",
  version: 1,
  entries: [
    "src/domain/core-operation-plan.ts",
    "src/application/core-operation-lifecycle.ts",
  ],
  excludedDerivedFiles: [identityPath, manifestPath],
  dependencies: "package-lock.json",
  files,
};
const sourceDigest = createHash("sha256")
  .update(JSON.stringify(meaning))
  .digest("hex");
const manifest = JSON.stringify({ ...meaning, sourceDigest }, null, 2) + "\n";
const source =
  "// Generated by scripts/generate-core-planner-identity.mjs; no self-hash.\nexport const corePlannerIdentity = Object.freeze(" +
  JSON.stringify({ format: meaning.format, version: 1, sourceDigest }) +
  ");\n";
if (process.argv.includes("--check")) {
  if (
    (await readFile(identityPath, "utf8")) !== source ||
    (await readFile(manifestPath, "utf8")) !== manifest
  )
    throw Error("CORE_PLANNER_SOURCE_IDENTITY_STALE");
  console.log(
    `Planner graph identity checked: ${sourceDigest} (${files.length} maintained files)`,
  );
} else {
  await writeFile(identityPath, source);
  await writeFile(manifestPath, manifest);
  console.log(
    `Planner graph identity generated: ${sourceDigest} (${files.length} maintained files)`,
  );
}
